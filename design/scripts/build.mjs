#!/usr/bin/env node
// =============================================================
// GateRook Design Kit · build
// -------------------------------------------------------------
// One command regenerates every derived file, so nothing is ever
// mirrored by hand:
//
//   tokens/tokens.json ─┬─▶ tokens/tokens.css      (CSS custom properties, all themes)
//                       ├─▶ scss/_tokens.scss      (SCSS variables + type ramp map)
//                       └─▶ scss/_tokens-css.scss  (same CSS, @use'd by index.scss)
//   scss/index.scss ───────▶ dist/gw-kit.css       (fonts + tokens + components + elements)
//   showcase/*.html ───────▶ pages/showcase.html   (stitched from per-component fragments)
//
// Usage: npm run build          (all)
//        npm run build -- --no-css   (skip sass, e.g. when sass is not installed)
// =============================================================

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = new Set(process.argv.slice(2));
const GENERATED = "GENERATED by scripts/build.mjs from tokens/tokens.json. Do not edit by hand.";

// ─────────────────────────── tokens ───────────────────────────

const MODES = ["dark", "light-hc", "dark-hc"];

/** Flatten the DTCG tree into [{ path: ["color","bg","canvas"], value, type, modes }] */
export function flattenTokens(tree) {
  const out = [];
  const walk = (node, path) => {
    if (node && typeof node === "object" && "$value" in node) {
      out.push({ path, value: node.$value, type: node.$type, modes: node.$extensions?.["gw.modes"] ?? {}, description: node.$description });
      return;
    }
    for (const [k, v] of Object.entries(node ?? {})) {
      if (k.startsWith("$")) continue;
      walk(v, [...path, k]);
    }
  };
  walk(tree, []);
  return out;
}

export function loadTokens() {
  const tree = JSON.parse(readFileSync(join(ROOT, "tokens/tokens.json"), "utf8"));
  const flat = flattenTokens(tree);
  const byPath = new Map(flat.map((t) => [t.path.join("."), t]));
  const resolve = (v, seen = new Set()) =>
    typeof v === "string"
      ? v.replace(/\{([^}]+)\}/g, (_, ref) => {
          if (seen.has(ref)) throw new Error(`Circular token reference: ${ref}`);
          const t = byPath.get(ref);
          if (!t) throw new Error(`Unknown token reference {${ref}}`);
          return resolve(t.value, new Set([...seen, ref]));
        })
      : v;
  for (const t of flat) {
    t.value = resolve(t.value);
    for (const m of Object.keys(t.modes)) t.modes[m] = resolve(t.modes[m]);
  }
  return flat;
}

export const cssVar = (path) => `--gw-${path.join("-")}`;
const isThemed = (t) => t.path[0] === "color" || t.path[0] === "shadow";

/** Value of a themed token in a given mode (falls back light-hc → light, dark-hc → dark → light). */
export function modeValue(t, mode) {
  if (mode === "light") return t.value;
  if (mode === "dark") return t.modes.dark ?? t.value;
  if (mode === "light-hc") return t.modes["light-hc"] ?? t.value;
  if (mode === "dark-hc") return t.modes["dark-hc"] ?? t.modes.dark ?? t.value;
  throw new Error(mode);
}

function buildTokensCss(flat) {
  const decl = (list, mode, onlyOverrides = false) =>
    list
      .filter((t) => !onlyOverrides || t.modes[mode] !== undefined)
      .map((t) => `  ${cssVar(t.path)}: ${mode ? modeValue(t, mode) : t.value};`)
      .join("\n");
  const themed = flat.filter(isThemed);
  const plain = flat.filter((t) => !isThemed(t));
  const darkBlock = `${decl(themed.filter((t) => t.modes.dark !== undefined), "dark")}\n  color-scheme: dark;`;
  const hc = (scheme) => decl(themed, `${scheme}-hc`, true);

  return `/*!
 * GateRook design tokens · CSS custom properties
 * ${GENERATED}
 *
 * Themes are attributes on <html> (or on any subtree for previews):
 *   data-theme="light" | "dark"          set by assets/theme-boot.js from the user's choice (system/light/dark)
 *   data-contrast="more" | "normal"      "more" = high contrast; absent = follow prefers-contrast
 * Without the attributes the tokens still follow prefers-color-scheme and prefers-contrast.
 */

/* ───────── base: light scheme + every non-colour token ───────── */
:root,
[data-theme="light"] {
${decl(themed, "light")}
  color-scheme: light;
}
:root {
${decl(plain)}
}

/* ───────── dark scheme ───────── */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${darkBlock.replace(/^/gm, "  ")}
  }
}
[data-theme="dark"] {
${darkBlock}
}

/* ───────── high contrast · light ───────── */
[data-theme="light"][data-contrast="more"] {
${hc("light")}
}
@media (prefers-contrast: more) {
  [data-theme="light"]:not([data-contrast]) {
${hc("light").replace(/^/gm, "  ")}
  }
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme])[data-contrast="more"] {
${hc("light").replace(/^/gm, "  ")}
  }
}
@media (prefers-color-scheme: light) and (prefers-contrast: more) {
  :root:not([data-theme]):not([data-contrast]) {
${hc("light").replace(/^/gm, "  ")}
  }
}

/* ───────── high contrast · dark ───────── */
[data-theme="dark"][data-contrast="more"] {
${hc("dark")}
}
@media (prefers-contrast: more) {
  [data-theme="dark"]:not([data-contrast]) {
${hc("dark").replace(/^/gm, "  ")}
  }
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme])[data-contrast="more"] {
${hc("dark").replace(/^/gm, "  ")}
  }
}
@media (prefers-color-scheme: dark) and (prefers-contrast: more) {
  :root:not([data-theme]):not([data-contrast]) {
${hc("dark").replace(/^/gm, "  ")}
  }
}
`;
}

function buildTokensScss(flat) {
  const lines = [
    "// =============================================================",
    `// ${GENERATED}`,
    "// -------------------------------------------------------------",
    "// $gw-* variables resolve to var(--gw-*) so compile-time use stays",
    "// themable. Breakpoints are raw values (media queries cannot read",
    "// custom properties). $gw-type is the type ramp map for gw-type().",
    "// =============================================================",
    "",
  ];
  for (const t of flat) {
    if (t.path[0] === "breakpoint") continue;
    lines.push(`$gw-${t.path.join("-")}: var(${cssVar(t.path)});`);
  }
  lines.push("", "// Breakpoints (raw, compile time)");
  for (const t of flat.filter((t) => t.path[0] === "breakpoint")) lines.push(`$gw-bp-${t.path[1]}: ${t.value};`);
  const roles = [...new Set(flat.filter((t) => t.path[0] === "type").map((t) => t.path[1]))];
  lines.push("", "// Type ramp: role → (size, line, weight, tracking) as custom-property references", "$gw-type: (");
  for (const r of roles) {
    lines.push(`  "${r}": (size: var(--gw-type-${r}-size), line: var(--gw-type-${r}-line), weight: var(--gw-type-${r}-weight), tracking: var(--gw-type-${r}-tracking)),`);
  }
  lines.push(");", "");
  return lines.join("\n");
}

// ─────────────────────────── showcase ───────────────────────────

/**
 * Every element marked data-sc-code gets a "Markup" disclosure right after it,
 * built from its own source: fragments never hand-escape example code.
 */
async function withMarkup(html) {
  if (!html.includes("data-sc-code")) return html;
  const { parseFragment } = await import("parse5");
  const doc = parseFragment(html, { sourceCodeLocationInfo: true });
  const hits = [];
  const walk = (n) => {
    if (n.attrs?.some((a) => a.name === "data-sc-code")) hits.push(n.sourceCodeLocation);
    (n.childNodes ?? []).forEach(walk);
  };
  walk(doc);
  hits.sort((a, b) => b.endOffset - a.endOffset);
  for (const loc of hits) {
    const inner = html.slice(loc.startTag.endOffset, loc.endTag ? loc.endTag.startOffset : loc.endOffset);
    const lines = inner.replace(/^\s*\n/, "").replace(/\s+$/, "").split("\n");
    const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^\s*/)[0].length));
    const code = lines.map((l) => l.slice(indent)).join("\n");
    const details = `\n<details class="sc-code"><summary>Markup</summary><pre><code>${esc(code)}</code></pre></details>`;
    html = html.slice(0, loc.endOffset) + details + html.slice(loc.endOffset);
  }
  return html;
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Foundations sections generated from tokens, so the docs can never drift from tokens.json. */
function foundationFragments(flat) {
  const colours = flat.filter((t) => t.path[0] === "color");
  const groups = [...new Set(colours.map((t) => t.path.slice(1, -1).join(".")))];
  const swatches = groups
    .map((g) => {
      const items = colours.filter((t) => t.path.slice(1, -1).join(".") === g);
      return `<h3>${esc(g)}</h3>\n<div class="sc-swatches">${items
        .map((t) => {
          const v = cssVar(t.path);
          const light = modeValue(t, "light"), dark = modeValue(t, "dark");
          return `<div class="sc-swatch"><span class="sc-swatch__chip" style="background: var(${v})"></span><span><span class="sc-swatch__name">${v}</span><br><span class="sc-swatch__val">${esc(light)}${dark !== light ? " · " + esc(dark) : ""}</span></span></div>`;
        })
        .join("")}</div>`;
    })
    .join("\n");
  const colorsHtml = `<section class="sc-section" id="colors" data-title="Colour" data-group="Foundations">
<h2>Colour <code class="gw-code">--gw-color-*</code></h2>
<p>Semantic tokens only: components never reference a hex value. Each swatch follows the current theme; values read light · dark. Every text and non-text pair is verified for WCAG 2.2 AA in light, dark and both high contrast modes by <code class="gw-code">npm run check</code> (<code class="gw-code">tokens/contrast-pairs.json</code>).</p>
<div class="sc-themes">
  <div data-theme="light"><p class="gw-text-overline">Light</p><p class="gw-text-h2">Approve and run</p><p class="gw-text-body-read">Exact statement, masked secrets.</p><p><button class="gw-btn gw-btn--primary" type="button">Create endpoint</button> <button class="gw-btn gw-btn--approve" type="button">Approve and run</button> <button class="gw-btn gw-btn--danger" type="button">Deny</button></p></div>
  <div data-theme="dark"><p class="gw-text-overline">Dark</p><p class="gw-text-h2">Approve and run</p><p class="gw-text-body-read">Exact statement, masked secrets.</p><p><button class="gw-btn gw-btn--primary" type="button">Create endpoint</button> <button class="gw-btn gw-btn--approve" type="button">Approve and run</button> <button class="gw-btn gw-btn--danger" type="button">Deny</button></p></div>
</div>
${swatches}
</section>`;

  const roles = [...new Set(flat.filter((t) => t.path[0] === "type").map((t) => t.path[1]))];
  const val = (r, k) => flat.find((t) => t.path.join(".") === `type.${r}.${k}`)?.value;
  const typeHtml = `<section class="sc-section" id="typography" data-title="Typography" data-group="Foundations">
<h2>Typography <code class="gw-code">gw-type()</code></h2>
<p><strong>Inter</strong> for the interface: drawn for screens, tabular figures, full Cyrillic, and the <code class="gw-code">cv05</code> / <code class="gw-code">cv08</code> alternates on so <code class="gw-code">l</code>, <code class="gw-code">I</code> and <code class="gw-code">1</code> never read alike. <strong>JetBrains Mono</strong> for everything literal: tool names, slugs, hosts, SQL, tokens, JSON. Ligatures are off in mono, because what a human approves must be exactly what runs. Both are self-hosted (OFL 1.1).</p>
<div class="sc-ramp">${roles
    .map((r) => `<div class="sc-ramp__row"><span class="sc-ramp__meta">${r}<br>${val(r, "size")} / ${val(r, "line")} / ${val(r, "weight")}</span><span class="gw-text-${r}">${r.startsWith("code") ? "SELECT id, status FROM orders WHERE id != 48213;" : r === "stat" ? "1,284" : r === "overline" ? "Waiting for approval" : "Approve the exact statement, not the agent's summary"}</span></div>`)
    .join("")}</div>
</section>`;

  const space = flat.filter((t) => t.path[0] === "space");
  const radius = flat.filter((t) => t.path[0] === "radius");
  const shadow = flat.filter((t) => t.path[0] === "shadow");
  const layoutHtml = `<section class="sc-section" id="space" data-title="Space, radius, elevation" data-group="Foundations">
<h2>Space, radius, elevation</h2>
<p>A 4px grid. Cards pad <code class="gw-code">--gw-space-5</code> and stack with <code class="gw-code">--gw-space-4</code>; page sections sit <code class="gw-code">--gw-space-8</code> apart. In dark the border carries the edge of a surface and shadows only separate floating layers.</p>
<h3>Space</h3>
<div class="sc-scale">${space.map((t) => `<div class="sc-scale__row"><span class="sc-ramp__meta">${cssVar(t.path)} · ${t.value}</span><span class="sc-scale__bar" style="width: var(${cssVar(t.path)})"></span></div>`).join("")}</div>
<h3>Radius</h3>
<div class="sc-boxes">${radius.map((t) => `<span class="sc-box" style="border-radius: var(${cssVar(t.path)})">${t.path[1]} · ${t.value}</span>`).join("")}</div>
<h3>Elevation</h3>
<div class="sc-boxes">${shadow.map((t) => `<span class="sc-box" style="box-shadow: var(${cssVar(t.path)}); border-radius: var(--gw-radius-md)">shadow-${t.path[1]}</span>`).join("")}</div>
</section>`;
  return [
    { name: "tokens:colors", html: colorsHtml },
    { name: "tokens:typography", html: typeHtml },
    { name: "tokens:space", html: layoutHtml },
  ];
}

async function buildShowcase(flat) {
  const dir = join(ROOT, "showcase");
  const tplPath = join(dir, "_template.html");
  if (!existsSync(tplPath)) return null;
  const files = readdirSync(dir).filter((f) => f.endsWith(".html") && !f.startsWith("_")).sort();
  const groups = new Map();
  const sections = [];
  const fragments = [...foundationFragments(flat), ...files.map((f) => ({ name: `showcase/${f}`, html: readFileSync(join(dir, f), "utf8").trim() }))];
  for (const { name: f, html: raw } of fragments) {
    const html = await withMarkup(raw);
    const m = html.match(/<section[^>]*\bid="([^"]+)"[^>]*\bdata-title="([^"]+)"[^>]*\bdata-group="([^"]+)"/) ||
      html.match(/<section[^>]*\bdata-title="([^"]+)"[^>]*\bdata-group="([^"]+)"[^>]*\bid="([^"]+)"/);
    if (!m) throw new Error(`${f}: first <section> needs id, data-title and data-group (in that order)`);
    const [, id, title, group] = m;
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push({ id, title });
    sections.push(`<!-- ▼ ${f} -->\n${html}\n<!-- ▲ ${f} -->`);
  }
  const nav = [...groups]
    .map(([g, items]) =>
      `<div class="sc-nav__group" role="group" aria-labelledby="sc-g-${slug(g)}"><p class="sc-nav__label" id="sc-g-${slug(g)}">${g}</p><ul>${items
        .map((i) => `<li><a href="#${i.id}">${i.title}</a></li>`)
        .join("")}</ul></div>`,
    )
    .join("\n");
  const out = readFileSync(tplPath, "utf8")
    .replace("<!-- @NAV -->", nav)
    .replace("<!-- @SECTIONS -->", sections.join("\n\n"))
    .replace("<!-- @GENERATED -->", `<!-- ${"GENERATED by scripts/build.mjs from showcase/*.html. Edit the fragments, not this file."} -->`);
  writeFileSync(join(ROOT, "pages/showcase.html"), out);
  return files.length;
}
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

// ─────────────────────────── run ───────────────────────────

async function main() {
  const flat = loadTokens();
  const css = buildTokensCss(flat);
  writeFileSync(join(ROOT, "tokens/tokens.css"), css);
  writeFileSync(join(ROOT, "scss/_tokens-css.scss"), `// ${GENERATED}\n// Plain CSS, emitted once by index.scss so dist/gw-kit.css is self-contained.\n${css}`);
  writeFileSync(join(ROOT, "scss/_tokens.scss"), buildTokensScss(flat));
  console.log(`tokens   ${flat.length} tokens → tokens/tokens.css, scss/_tokens.scss`);

  if (!args.has("--no-css")) {
    let sass;
    try {
      sass = await import("sass");
    } catch {
      console.error("sass is not installed. Run `npm install` in design/ (or pass --no-css).");
      process.exit(1);
    }
    const res = sass.compile(join(ROOT, "scss/index.scss"), { style: "expanded", sourceMap: false, loadPaths: [ROOT] });
    const banner = `/*!\n * GateRook Design Kit · dist/gw-kit.css\n * GENERATED by scripts/build.mjs from scss/index.scss. Do not edit by hand.\n * Link this one file; it carries fonts, tokens (all themes), reset, components and elements.\n */\n`;
    writeFileSync(join(ROOT, "dist/gw-kit.css"), banner + res.css + "\n");
    console.log(`css      dist/gw-kit.css (${(res.css.length / 1024).toFixed(1)} KB)`);
  }

  const n = await buildShowcase(flat);
  if (n !== null) console.log(`showcase ${n} fragments → pages/showcase.html`);
}

if (process.argv[1] && basename(process.argv[1]) === "build.mjs") main().catch((e) => { console.error(e.message); process.exit(1); });
