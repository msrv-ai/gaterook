#!/usr/bin/env node
// Build the plugin host's Java 25 runtime on the target operating system.
import { spawnSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const defaultOutput = join(root, 'target', 'plugin-host-jre');
const marker = '.gaterook-jlink';
const markerText = 'Generated by scripts/jlink.mjs.\n';

// Plugins declare their own module requirements, so retain the full Java SE API and common JDK modules.
export const JRE_MODULES = Object.freeze([
  'java.se', 'jdk.unsupported', 'jdk.crypto.cryptoki', 'jdk.zipfs', 'jdk.net', 'jdk.charsets', 'jdk.localedata',
  'jdk.security.auth', 'jdk.security.jgss', 'jdk.naming.dns', 'jdk.management', 'jdk.httpserver', 'jdk.jfr',
  'jdk.management.jfr',
]);

export function parseRuntimeVersion(settings) {
  const version = /^\s*java\.runtime\.version\s*=\s*(\S+)\s*$/m.exec(settings)?.[1];
  if (!version) throw new Error('Could not read java.runtime.version from JAVA_HOME.');
  if (!/^25(?:[.+-]|$)/.test(version)) throw new Error(`The plugin host requires Java 25; JAVA_HOME provides ${version}.`);
  return version;
}

function checkDestination(output) {
  let entry;
  try { entry = lstatSync(output); }
  catch (error) { if (error.code === 'ENOENT') return; throw error; }
  if (!entry.isDirectory() || entry.isSymbolicLink()) throw new Error(`Refusing to replace a non-directory or symlink: ${output}`);
  if (!readdirSync(output).length) return;
  const stamp = join(output, marker);
  if (existsSync(stamp) && lstatSync(stamp).isFile() && readFileSync(stamp, 'utf8') === markerText) return;
  // Accept the original shell script's runtime at its established default location only.
  const release = join(output, 'release');
  if (output === defaultOutput && existsSync(release) && existsSync(join(output, 'lib', 'modules'))
      && /^JAVA_RUNTIME_VERSION="25(?:[.+-]|"|$)/m.test(readFileSync(release, 'utf8'))
      && ['java', 'java.exe'].some((name) => existsSync(join(output, 'bin', name)))) return;
  throw new Error(`Refusing to replace ${output}: it is not a generated GateRook JRE. Choose an empty output directory.`);
}

export function createJre(output = defaultOutput, {
  javaHome = process.env.JAVA_HOME, platform = process.platform, run = spawnSync,
} = {}) {
  if (!javaHome) throw new Error('Set JAVA_HOME to a JDK 25 before building the plugin-host runtime.');
  if (typeof output !== 'string' || !output.trim()) throw new Error('A nonempty output path is required.');
  output = resolve(output);
  checkDestination(output);
  const executable = (name) => join(javaHome, 'bin', `${name}${platform === 'win32' ? '.exe' : ''}`);
  const settings = run(executable('java'), ['-XshowSettings:properties', '-version'], { encoding: 'utf8' });
  if (settings.error || settings.status !== 0) {
    throw new Error(`Could not run JAVA_HOME/bin/java: ${settings.error?.message ?? settings.stderr ?? settings.signal ?? settings.status}`);
  }
  const version = parseRuntimeVersion(`${settings.stdout ?? ''}\n${settings.stderr ?? ''}`);
  mkdirSync(dirname(output), { recursive: true });
  const temporary = mkdtempSync(join(dirname(output), '.gaterook-jlink-'));
  const built = join(temporary, 'runtime');
  try {
    const result = run(executable('jlink'), [
      '--add-modules', JRE_MODULES.join(','), '--include-locales=en,ru', '--strip-debug', '--no-man-pages',
      '--no-header-files', '--compress=zip-6', `--release-info=add:JAVA_RUNTIME_VERSION=${version}`, '--output', built,
    ], { stdio: 'inherit' });
    if (result.error || result.status !== 0) {
      throw new Error(`jlink failed: ${result.error?.message ?? result.signal ?? result.status}`);
    }
    if (!existsSync(join(built, 'release')) || !existsSync(join(built, 'lib', 'modules'))
        || !existsSync(join(built, 'bin', platform === 'win32' ? 'java.exe' : 'java'))) {
      throw new Error('jlink did not produce a complete runtime.');
    }
    writeFileSync(join(built, marker), markerText);
    // Preserve the previous runtime until the new one has finished successfully.
    checkDestination(output);
    rmSync(output, { recursive: true, force: true });
    renameSync(built, output);
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
  console.log(`jlink: ${output}, JAVA_RUNTIME_VERSION=${version}`);
  return output;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    if (process.argv.length > 3 || process.argv[2]?.startsWith('-')) throw new Error('Usage: node scripts/jlink.mjs [output-directory]');
    createJre(process.argv[2]);
  } catch (error) {
    console.error(`jlink: ${error.message}`);
    process.exitCode = 2;
  }
}
