package com.gaterook.connectors.aws;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.zip.GZIPInputStream;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The AWS API catalog of {@code aws_api_read} and {@code aws_api_change}: one entry per service of
 * {@code github.com/aws/api-models-aws}, generated by {@code scripts/aws-api-catalog.py} into
 * {@code connectors/aws/api/} (an index, and a gzipped model per service with its protocol, endpoints, operations and
 * shapes, without documentation). The index is read once; a service's model when a call first names it, and the last
 * {@value #LOADED} models stay in memory.
 *
 * <p>Agents name a service as the AWS CLI does ({@code ecs}, {@code elbv2}, {@code logs}, {@code ce}) or by an alias
 * the generator found unambiguous (the SDK ID's slug {@code elastic-load-balancing-v2}, its endpoint prefix, its
 * signing name); case, spaces and underscores don't matter.
 */
final class ApiCatalog {

  static final String BASE = "connectors/aws/api/";
  /** Service models kept parsed; EC2's is the largest (about 1.2 MB of JSON). */
  static final int LOADED = 12;
  private static final JsonMapper JSON = JsonMapper.builder().build();
  private static volatile ApiCatalog shared;

  /** One service of the index. {@code unsupported} says why the AWS API tools can't call it, or is {@code null}. */
  record Entry(String name, String sdkId, String protocol, String iam, int operations, String unsupported) {}

  private final String revision;
  private final Map<String, Entry> entries;
  private final Map<String, String> spellings;
  private final Map<String, ApiModel> loaded = Collections.synchronizedMap(new LinkedHashMap<>(16, 0.75f, true) {
    private static final long serialVersionUID = 1L;

    @Override
    protected boolean removeEldestEntry(Map.Entry<String, ApiModel> eldest) {
      return size() > LOADED;
    }
  });

  private ApiCatalog(JsonNode index) {
    this.revision = index.path("revision").asString("");
    Map<String, Entry> byName = new LinkedHashMap<>();
    Map<String, List<String>> claims = new HashMap<>();
    for (Map.Entry<String, JsonNode> e : index.path("services").properties()) {
      JsonNode s = e.getValue();
      String name = e.getKey();
      byName.put(name, new Entry(name, s.path("sdkId").asString(name), s.path("protocol").asString(""),
          s.path("iam").asString(name), s.path("operations").asInt(0),
          s.hasNonNull("unsupported") ? s.get("unsupported").asString() : null));
      claim(claims, name, name);
      for (JsonNode alias : s.path("aliases")) {
        claim(claims, alias.asString(""), name);
      }
    }
    Map<String, String> out = new HashMap<>();
    // A service's own name wins over another's alias; a spelling two services claim names neither.
    claims.forEach((spelling, names) -> {
      if (names.size() == 1) {
        out.put(spelling, names.getFirst());
      } else if (byName.containsKey(spelling)) {
        out.put(spelling, spelling);
      }
    });
    this.entries = Map.copyOf(byName);
    this.spellings = Map.copyOf(out);
  }

  private static void claim(Map<String, List<String>> claims, String spelling, String name) {
    for (String key : keys(spelling)) {
      List<String> names = claims.computeIfAbsent(key, k -> new ArrayList<>(1));
      if (!names.contains(name)) {
        names.add(name);
      }
    }
  }

  /** {@code Elastic Load Balancing v2} → {@code elastic-load-balancing-v2} and {@code elasticloadbalancingv2}. */
  private static List<String> keys(String spelling) {
    String k = spelling.strip().toLowerCase(Locale.ROOT).replace('_', '-').replace(' ', '-');
    String compact = k.replace("-", "");
    return k.equals(compact) ? List.of(k) : List.of(k, compact);
  }

  /** The catalog this connector ships. */
  static ApiCatalog shared() {
    ApiCatalog c = shared;
    if (c == null) {
      synchronized (ApiCatalog.class) {
        c = shared;
        if (c == null) {
          c = new ApiCatalog(read(BASE + "index.json", false));
          shared = c;
        }
      }
    }
    return c;
  }

  /** The commit of the models this catalog was generated from. */
  String revision() {
    return revision;
  }

  int size() {
    return entries.size();
  }

  /** The service an agent named, or {@code null}. */
  Entry find(String service) {
    if (service == null) {
      return null;
    }
    for (String key : keys(service)) {
      String name = spellings.get(key);
      if (name != null) {
        return entries.get(name);
      }
    }
    return null;
  }

  /** The model of a callable service. */
  ApiModel model(Entry e) {
    if (e.unsupported() != null) {
      throw new IllegalArgumentException(e.name() + " has no model: " + e.unsupported());
    }
    ApiModel m = loaded.get(e.name());
    if (m == null) {
      m = new ApiModel(read(BASE + "services/" + e.name() + ".json.gz", true));
      loaded.put(e.name(), m);
    }
    return m;
  }

  private static JsonNode read(String resource, boolean gzip) {
    InputStream in = ApiCatalog.class.getClassLoader().getResourceAsStream(resource);
    if (in == null) {
      throw new IllegalStateException("The AWS API catalog lacks " + resource);
    }
    try (InputStream raw = in; InputStream body = gzip ? new GZIPInputStream(raw, 65_536) : raw) {
      return JSON.readTree(body);
    } catch (IOException e) {
      throw new UncheckedIOException("The AWS API catalog's " + resource + " can't be read", e);
    }
  }
}
