#!/usr/bin/env node
// Generates ui/src/app/kit/icons.generated.ts: every Lucide icon the design kit uses, as @lucide/angular icon data.
//
// The kit names icons in markup (`data-lucide="trash-2"`) and in kit.js; @lucide/angular 1.49.0 (= design/vendor/lucide)
// exports them as classes whose static `icon` carries the canonical name, the SVG nodes and the aliases (`LucideTrash`:
// trash + trash-2). provideLucideIcons(...) registers name and aliases, so `<svg lucideIcon="trash-2">` keeps the kit's
// spelling.
//
// Why data and not the classes: the package's icon classes carry static fields that the bundler can't prove free of
// side effects, so importing even a few of them pulls all ~1,700 icons (725 kB) into the initial bundle. The plain
// `LucideIconData` objects copied here from the same package are exactly what the classes would register.
//
// Usage: node ui/scripts/kit-icons.mjs [--check]   (--check: exit 1 when the generated file is out of date)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const UI = join(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = join(UI, '..');
const DESIGN = join(ROOT, 'design');
const OUT = join(UI, 'src/app/kit/icons.generated.ts');

/** Icon names the app uses beyond the kit's markup (none may fall outside the kit: AGENTS.md §4). */
const EXTRA = [];

function kitNames() {
  const names = new Set(EXTRA);
  for (const dir of ['pages', 'elements', 'showcase']) {
    for (const f of readdirSync(join(DESIGN, dir)).filter((n) => n.endsWith('.html'))) {
      const html = readFileSync(join(DESIGN, dir, f), 'utf8');
      for (const m of html.matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(m[1]);
    }
  }
  const kit = readFileSync(join(DESIGN, 'assets/kit.js'), 'utf8');
  for (const m of kit.matchAll(/data-lucide="([a-z0-9-]+)"/g)) if (m[1] !== 'name') names.add(m[1]);
  for (const m of kit.matchAll(/(?:success|warning|danger|info|neutral|brand): "([a-z0-9-]+)"/g)) names.add(m[1]);
  names.add('timer-off');
  return [...names].sort();
}

/** name or alias → { cls, data } where data is the class's static `icon` object (evaluated from the package). */
function lucideIndex() {
  const pkg = join(ROOT, 'node_modules/@lucide/angular/fesm2022/lucide-angular.mjs');
  const src = readFileSync(pkg, 'utf8');
  const index = new Map();
  const re = /class (Lucide[A-Za-z0-9]+) extends LucideIconBase \{\n(\s+)static icon = (\{\n[\s\S]*?\n\2\});/g;
  for (const m of src.matchAll(re)) {
    const [, cls, , literal] = m;
    // The literal is plain JSON-like data from the pinned package (names, sizes, SVG attributes): no code.
    const data = Function(`"use strict"; return (${literal});`)();
    const entry = { cls, data };
    if (!index.has(data.name)) index.set(data.name, entry);
    for (const a of data.aliases ?? []) if (!index.has(a)) index.set(a, entry);
  }
  return index;
}

function generate() {
  const names = kitNames();
  const index = lucideIndex();
  const missing = names.filter((n) => !index.has(n));
  if (missing.length) {
    console.error(`No @lucide/angular icon for: ${missing.join(', ')}`);
    process.exit(1);
  }
  const entries = [...new Map(names.map((n) => [index.get(n).cls, index.get(n)])).values()].sort((a, b) =>
    a.data.name.localeCompare(b.data.name),
  );
  const lines = [
    '// Generated by ui/scripts/kit-icons.mjs from the design kit and @lucide/angular 1.49.0: do not edit.',
    `// ${names.length} kit icon names → ${entries.length} icons (aliases keep the kit's spelling).`,
    "import type { LucideIconData } from '@lucide/angular';",
    '',
    '/** Every icon the kit uses (the `icon` data of the @lucide/angular class named in each comment). */',
    'export const KIT_ICONS: readonly LucideIconData[] = [',
    ...entries.map((e) => `  // ${e.cls}\n  ${JSON.stringify(e.data)},`),
    '];',
    '',
    '/** The kit\'s icon names (data-lucide values), for the registration test. */',
    `export const KIT_ICON_NAMES: readonly string[] = [\n${names.map((n) => `  '${n}',`).join('\n')}\n];`,
    '',
  ];
  return lines.join('\n');
}

const text = generate();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('ui/src/app/kit/icons.generated.ts is out of date: run node ui/scripts/kit-icons.mjs');
    process.exit(1);
  }
  console.log('icons.generated.ts is up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
