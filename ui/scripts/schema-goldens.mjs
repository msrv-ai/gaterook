#!/usr/bin/env node
// Golden files for the JSON Schema form renderer (ARCHITECTURE.md §8.3): the connector config schemas the core serves
// (`GET /api/connector-types/{type}/form?env=dev`, reports 04–12) and what the renderer makes of each — every field's
// widget, section, row, secret and branch condition, plus the value it would send for the defaults.
//
//   node ui/scripts/schema-goldens.mjs            # rewrite the goldens from the stored schemas
//   node ui/scripts/schema-goldens.mjs --fetch    # first fetch the schemas from a running dev loop (ui/scripts/dev.mjs)
//   node ui/scripts/schema-goldens.mjs --schema logs=connectors/logs/src/main/resources/connectors/logs/config.schema.json
//
// Output: ui/src/testing/connector-schemas.ts (generated; the spec src/app/schema-form/goldens.spec.ts compares the
// renderer with it). A change of a golden is a change of the form a person sees: review the diff.
import { build } from 'esbuild';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(ui, 'src/testing/connector-schemas.ts');
const TYPES = ['postgres', 'mysql', 'sqlserver', 'mongodb', 'redis', 'ssh', 'ssh-logs', 'logs', 'gcp-logging', 'loki', 'cloudwatch', 'opensearch', 'kubernetes', 'gcp', 'aws', 'http', 'mcp-server'];
const base = process.env.GW_DEV_URL ?? 'http://127.0.0.1:4311';

let schemas;
if (process.argv.includes('--fetch')) {
  schemas = {};
  for (const t of TYPES) {
    const res = await fetch(`${base}/api/connector-types/${t}/form?env=dev`);
    if (!res.ok) throw new Error(`${t}: HTTP ${res.status} from ${base} (is the dev loop running?)`);
    schemas[t] = (await res.json()).schema;
  }
} else {
  const text = readFileSync(out, 'utf8');
  const m = /export const CONNECTOR_FORMS: Readonly<Record<string, JsonObject>> = (\{[\s\S]*?\n\});\n/.exec(text);
  if (!m) throw new Error(`no CONNECTOR_FORMS in ${out}: run with --fetch`);
  schemas = JSON.parse(m[1]);
}

// Refresh individual schemas directly from their canonical sources without changing other stored fixtures.
for (let i = 2; i < process.argv.length; i++) {
  if (process.argv[i] !== '--schema') continue;
  const value = process.argv[++i] ?? '';
  const separator = value.indexOf('=');
  const type = value.slice(0, separator);
  const source = value.slice(separator + 1);
  if (separator < 1 || !TYPES.includes(type) || !source) {
    throw new Error('--schema requires a known connector type and source path: --schema logs=path/to/config.schema.json');
  }
  schemas[type] = JSON.parse(readFileSync(source, 'utf8'));
}

// Bundle the renderer's pure compiler for Node and run it on every schema.
const dir = mkdtempSync(join(tmpdir(), 'gw-goldens-'));
try {
  const file = join(dir, 'compile.mjs');
  await build({
    entryPoints: [join(ui, 'src/app/schema-form/goldens.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile: file,
    logLevel: 'silent',
  });
  const { golden } = await import(pathToFileURL(file).href);
  const goldens = Object.fromEntries(TYPES.map((t) => [t, golden(schemas[t])]));
  const header =
    '// Generated by ui/scripts/schema-goldens.mjs: do not edit. The connector form schemas of the core (env dev) and\n' +
    "// what the renderer makes of them; src/app/schema-form/goldens.spec.ts keeps the renderer to it.\n" +
    "import { JsonObject } from '../app/core/api/types';\n" +
    "import { FormGolden } from '../app/schema-form/goldens';\n\n";
  writeFileSync(
    out,
    `${header}export const CONNECTOR_FORMS: Readonly<Record<string, JsonObject>> = ${JSON.stringify(schemas, null, 2)};\n\n` +
      `export const CONNECTOR_GOLDENS: Readonly<Record<string, FormGolden>> = ${JSON.stringify(goldens, null, 2)};\n`,
  );
  console.log(`wrote ${out}: ${TYPES.length} schemas`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
